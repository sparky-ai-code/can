/** Rows of the glyph for a character code (32 to 126), as seven strings of five characters. */
export function glyphRows(code) {
  const i = code - FIRST_CHAR;
  if (i < 0 || i >= GLYPHS.length) return null;
  return GLYPHS[i].split('/');
}

